// Generates src/app/shared/icons.generated.ts from @tabler/icons, keeping only the icons the
// app uses. The component renders the shapes as SVG elements, so no markup string ever goes
// through innerHTML and the Trusted Types policy stays untouched.
//   node scripts/gen-icons.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS = [
  'alert-circle',
  'alert-triangle',
  'arrow-left',
  'check',
  'circle-check',
  'clock-hour-4',
  'copy',
  'external-link',
  'eye',
  'eye-off',
  'key',
  'lock',
  'logout',
  'menu-2',
  'refresh',
  'search',
  'settings',
  'wand',
  'x',
];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Hoisted to the workspace root or local to web, resolved the way Node does.
function packageDir(name) {
  for (let d = root; ; d = dirname(d)) {
    const candidate = join(d, 'node_modules', name);
    if (existsSync(candidate)) return candidate;
    if (dirname(d) === d) throw new Error(`${name} is not installed`);
  }
}
const dir = join(packageDir('@tabler/icons'), 'icons/outline');
const attr = /([a-z-]+)="([^"]*)"/g;
const out = {};
for (const name of ICONS) {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  out[name] = [...body.matchAll(/<(path|circle|rect|line|polyline|ellipse)\s([^>]*?)\/?>/g)]
    .map(([, tag, attrs]) => [
      tag,
      Object.fromEntries([...attrs.matchAll(attr)].map(([, k, v]) => [k, v])),
    ])
    // Tabler prefixes every icon with an invisible bounding box path.
    .filter(([, a]) => a.stroke !== 'none');
  // The component renders paths only. Fail loudly if Tabler ever ships another shape.
  const other = out[name].find(([tag]) => tag !== 'path');
  if (other) throw new Error(`${name} uses <${other[0]}>, extend the Icon component first`);
}

const ts = `// Generated by scripts/gen-icons.mjs from @tabler/icons (MIT). Do not edit by hand.
export type IconNode = readonly [tag: string, attrs: Readonly<Record<string, string>>];

export const ICONS = {
${Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n')}
} as const satisfies Record<string, readonly IconNode[]>;

export type IconName = keyof typeof ICONS;
`;
writeFileSync(join(root, 'src/app/shared/icons.generated.ts'), ts);
console.log(`wrote ${ICONS.length} icons`);
